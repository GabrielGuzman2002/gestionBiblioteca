    //boton de registrar y sus metodos
    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
       String id = txtId.getText().trim();
       String nombre = txtNombre.getText().trim();
       String apellido = txtApellido.getText().trim();
       String telefono = txtTelefono.getText().trim();
       String correo = txtCorreo.getText().trim();
       
       if (id.isEmpty() || nombre.isEmpty() || apellido.isEmpty()|| correo.isEmpty()){
           JOptionPane.showMessageDialog(this, "Por favor complete todos los campos que son obligatorios");
           return;
       }
       
       //se crea la validacion del correo que lleve @
       if (!esCorreoValido(correo)){
           JOptionPane.showMessageDialog(this, "El correo que ha sido ingresado es invalido, por favro introdusca un correo valido con un dominio valido (Ejemplo, @gmail.com)");
           txtCorreo.requestFocus(); //hace que el cursor regrese al campo de correo
           return;
       }
       Usuario nuevo = new Usuario(id, nombre, apellido,telefono, correo, java.time.LocalDate.now());
       
       //se valida que el usuario se registre correctamente si nunca ha sido registrado
       if (usuarioDAO.registrar(nuevo)){
           JOptionPane.showMessageDialog(this, "El usuario se ha registrado con exito");
           limpiarCampos();
           cargarTabla(usuarioDAO.listarTodos());
       }
       else {
           JOptionPane.showMessageDialog(this,"No se ha podido registrar al usuairo, por favor reisar si el Id o el Correo ya existen");
       }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    
    //se crea los metodos del boton modificar
    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        
        String id = txtId.getText().trim();
        String correo = txtCorreo.getText().trim();
        
        //se valida el correo
        if (!correo.isEmpty() && !esCorreoValido(correo)){
            JOptionPane.showMessageDialog(this, "El correo que se ha ingresao no es valido, debe incluir @ y un dominio valido0","correo Invalido", JOptionPane.WARNING_MESSAGE);
            txtCorreo.requestFocus();
            return;
        }
        
        if (id.isEmpty()){
            JOptionPane.showMessageDialog(this,"Por favor primero seleccione un usuario de la tabla");
            return;
        }
        
        Usuario usu = new Usuario();
        usu.setId_Usuario(id);
        usu.setNombre(txtNombre.getText().trim());
        usu.setApellido(txtApellido.getText().trim());
        usu.setTelefono(txtTelefono.getText().trim());
        usu.setCorreoElectronico(txtCorreo.getText().trim());
        
        //se hace la validacion para modificar el usuario mandando a llamar a su metodo
        if (usuarioDAO.modificar(usu)){
            JOptionPane.showMessageDialog(this, "El usuario se ha modificado de forma exitosa");
            limpiarCampos();
            cargarTabla(usuarioDAO.listarTodos());
        }
        else{
            JOptionPane.showMessageDialog(this, "Error Al intentar modificar en la base de datos");
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    //Se cre el boton eliminar
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
      
        String id = txtId.getText().trim();
        
        if (id.isEmpty()){
            JOptionPane.showMessageDialog(this, "Seleccione uno de los usuarios que desea eliminar");
            return;
        }
        
        //se hace la validacion de los prestamos que estan activos
        if (usuarioDAO.prestamosActivos(id)){
            JOptionPane.showMessageDialog(this, "!No se ha podido eliminar el usuairo de la base de datos, "
                    + "El usuario presenta prestamos activos que estan pendientes", "Eliminacion denegada", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int respuesta = JOptionPane.showConfirmDialog(this, "¿Esta seguro/a que desea eliminar al usuario" + id + "?","Confirmar", JOptionPane.YES_NO_OPTION);
        
        if (respuesta == JOptionPane.YES_OPTION){
            if(usuarioDAO.eliminar(id)){
                JOptionPane.showMessageDialog(this, "El usuario se ha eliminado correctamente");
                limpiarCampos();
                cargarTabla(usuarioDAO.listarTodos());
            }
            else{
                JOptionPane.showMessageDialog(this, "Error: No ce ha podido eliminar los datos de la base de datos");
            }
        }
        
    }//GEN-LAST:event_btnEliminarActionPerformed

    
