    public void cargarTabla(List<Usuario>lista){
        
        for (Usuario usu : lista){
            modeloTabla.addRow(new Object[]{
                usu.getId_Usuario(),
                usu.getNombre(),
                usu.getApellido(),
                usu.getTelefono(),
                usu.getCorreoElectronico(),
                usu.getFechaRegistro()
            });
        }
    }
    
    public void limpiarCampos(){
        txtId.setText(" ");
        txtId.setEnabled(true);
        txtNombre.setText("");
        txtApellido.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        tablaUsuario.clearSelection();
        
    }
    
    //se valida que el correo tenga el formato correcto;
    private boolean esCorreoValido(String correo){
        String patron = "^[\\w.-]+@[a-zA-Z\\d.-]+\\.[a-zA-Z]{2,}$";
        return correo.matches(patron);
    }

