    private void tablaPrestamoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaPrestamoMouseClicked

        int fila = tablaPrestamo.getSelectedRow();
        if (fila >= 0) {
            
            txtIdPrestamo.setText(tablaPrestamo.getValueAt(fila, 0).toString());
            txtCodigoMaterial.setText(tablaPrestamo.getValueAt(fila, 1).toString());
            txtUsuario.setText(tablaPrestamo.getValueAt(fila, 4).toString());
         }
         
    }//GEN-LAST:event_tablaPrestamoMouseClicked

    private void btnDevolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDevolverActionPerformed
        String idPrestamo = txtIdPrestamo.getText().trim();
        String idMaterial = txtCodigoMaterial.getText().trim();

        if (idPrestamo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, aga una seleccion de un prestamo activo");
            return;
        }
        int confirmacion = JOptionPane.showConfirmDialog(this, "¿Desea hacer el registro de la devolucion de este material?", "Confirmar", JOptionPane.YES_NO_OPTION);

        if (confirmacion == JOptionPane.YES_OPTION) {
            boolean exito = prestamoDAO.registrarDevolucion(idPrestamo, idMaterial);

            if (exito) {
                JOptionPane.showMessageDialog(this, "¡La devolucion s eha registrado de forma exitosa! \nEl Material se encuentrea nuevamente disponible");
                txtIdPrestamo.setText(" ");
                txtCodigoMaterial.setText(" ");
                txtUsuario.setText(" ");
                cargarTabla();
                //Se vuelve a realizar la consulta en MySQL para revisar que el prestamo ya no aparesca

            } else {
                JOptionPane.showMessageDialog(this, "Eror no ce ha podido hacer el registro de la devolucion en la base de datos");

            }
        }
    }//GEN-LAST:event_btnDevolverActionPerformed

