    //se crea el boton para poder generar el reporte de la biblioteca
    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
       //variables que se usaran para guardar los conteos
       int totalMateriales = 0;
       int librosDisponibles = 0;
       int totalUsuarios = 0;
       int prestamosActivos = 0;
       int prestamosDevueltos = 0;
       
       try (java.sql.Connection con = Conexion.obtenerConexion()){
           if (con == null){
               javax.swing.JOptionPane.showMessageDialog(this, "Error no hay una conexion con la base de datos",
                       "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
               return;
           }
           
           //se hace el conteo de todos los materiales
           try (java.sql.PreparedStatement ps = con.prepareStatement("Select count(*), sum(case "
                   + "when disponible = true then 1 else 0 end) from material_bibliografico");
                   java.sql.ResultSet rs = ps.executeQuery()){
                   
                   if (rs.next()){
                       totalMateriales = rs.getInt(1);  
                       librosDisponibles = rs.getInt(2);
          }
       }
           
           //conteo de los usuarios
           try (java.sql.PreparedStatement ps = con.prepareStatement("Select Count (*) from usuario");
                   java.sql.ResultSet rs = ps.executeQuery()){
               if (rs.next()){
                   totalUsuarios = rs.getInt(1);
               }
           }
           
           
           //conteo de los prestamos
           try (java.sql.PreparedStatement ps = con.prepareStatement("Select " + "sum"
                   + "(case when activo = true then 1 else 0 end)," +
                   "Sum(case when activo = false then 1 else 0 end) " + "from prestamo");
                   java.sql.ResultSet rs = ps.executeQuery()){
               if (rs.next()){
                   
                   prestamosActivos = rs.getInt(1);
                   prestamosDevueltos = rs.getInt(2);
               }
           }
           
           //se hace la creacion del reporte 
           String reporte = "=================================\n "
                   + "REPORTE DE LA BIBLIOTECA \n "
                   + "=========================================\n\n "
                   + "[Materiales Bibliograficos ] \n"
                   + "*Total regitrados: " + totalMateriales + "\n "
                   + "*Disponibles para prestamos: " + librosDisponibles + "\n"
                   + "*Prestados Actualmente: " + (totalMateriales - librosDisponibles) +"\n\n"
                   + "[USUARIOS] \n"
                   + "*Total de usuarios registrados: " + totalUsuarios + "\n\n"
                   + "[PRESTAMOS Y DEVOLUCIONES]\n"
                   + "*Prestamos Activos (Pendientes): " + prestamosActivos + "\n"
                   + "*Devoluciones que se han completado : " + prestamosDevueltos+ "\n"
                   + "*Total historial de operaciones realizadas: " + (prestamosActivos + prestamosDevueltos)+ "\n\n"
                   + "+Fecha de emision: "+ java.time.LocalDate.now();
           
           //Se muestra el report en un cuadro en consola
           javax.swing.JTextArea txtArea= new javax.swing.JTextArea(reporte);
           
           txtArea.setFont(new java.awt.Font("Monospace", java.awt.Font. PLAIN, 13));
           txtArea.setEditable(false);
           javax.swing.JOptionPane.showMessageDialog(this, new javax.swing.JScrollPane(txtArea), 
                "Reporte generado del sistema", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }
catch (java.sql.SQLException e){
    javax.swing.JOptionPane.showMessageDialog(this, "Error no ce ha podido hacer la generacion del reporte: "
            + "" + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
     
       }
    }//GEN-LAST:event_btnGenerarReporteActionPerformed


